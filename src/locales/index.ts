export function t(language: Language, text: string) {
  if (language !== 'en') return text;
  if (english[text]) return english[text];
  const missingResource = text.match(/^备份需要的资源 (.+) 不存在$/);
  if (missingResource) return `Required backup resource ${missingResource[1]} is missing`;
  const remoteStatus = text.match(/^远端服务返回 (\d+)$/);
  if (remoteStatus) return `The remote service returned ${remoteStatus[1]}`;
  return text;
}
